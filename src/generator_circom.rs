use crate::parser::CircomVerificationKey;

/// Generates a complete, standalone, ultra-lean Soroban smart contract for Circom Groth16.
/// Uses native host functions for G1 Multi-Scalar Multiplication (MSM) and Pairing checks.
pub fn generate_circom_contract(vk: &CircomVerificationKey) -> String {
    let alpha_bytes = format_hex_array(&[
        crate::parser::parse_hex_or_dec_32(&vk.vk_alpha_1[0]),
        crate::parser::parse_hex_or_dec_32(&vk.vk_alpha_1[1]),
    ]);

    let beta_bytes = format_hex_g2(&vk.vk_beta_2);
    let gamma_bytes = format_hex_g2(&vk.vk_gamma_2);
    let delta_bytes = format_hex_g2(&vk.vk_delta_2);

    let ic0_bytes = format_hex_array(&[
        crate::parser::parse_hex_or_dec_32(&vk.ic[0][0]),
        crate::parser::parse_hex_or_dec_32(&vk.ic[0][1]),
    ]);

    // IC[1..] for MSM
    let _num_ic_rest = vk.ic.len().saturating_sub(1);
    let mut ic_rest_code = String::new();
    for (idx, ic_pt) in vk.ic.iter().skip(1).enumerate() {
        let b = format_hex_array(&[
            crate::parser::parse_hex_or_dec_32(&ic_pt[0]),
            crate::parser::parse_hex_or_dec_32(&ic_pt[1]),
        ]);
        ic_rest_code.push_str(&format!("    // IC[{}]\n    points.push_back(G1Affine::from_bytes(BytesN::from_array(&env, &{})));\n", idx + 1, b));
    }

    format!(r#"// ==============================================================================
// AUTO-GENERATED BY NANASI: Lean Soroban ZK Verifier
// Curve: BN254 | Proof System: Groth16 (Circom / SnarkJS)
// Features: Zero crypto dependencies, O(1) Single-Call G1 MSM, Native Pairing Check
// Target Size: < 15 KB WASM | Typical Gas: ~3M - 5M CPU instructions
// ==============================================================================
#![no_std]
use soroban_sdk::{{
    contract, contractimpl, BytesN, Env, Vec, vec,
    crypto::bn254::{{Bn254Fr, Bn254G1Affine as G1Affine, Bn254G2Affine as G2Affine}},
}};

pub const VK_ALPHA_G1: [u8; 64] = {alpha_bytes};
pub const VK_BETA_G2: [u8; 128] = {beta_bytes};
pub const VK_GAMMA_G2: [u8; 128] = {gamma_bytes};
pub const VK_DELTA_G2: [u8; 128] = {delta_bytes};
pub const VK_IC_0: [u8; 64] = {ic0_bytes};

pub const NUM_PUBLIC_INPUTS: usize = {num_public_inputs};

#[contract]
pub struct CircomGroth16Verifier;

#[contractimpl]
impl CircomGroth16Verifier {{
    /// Verifies a Groth16 proof using Stellar's native BN254 host precompiles (CAP-0074).
    ///
    /// - proof_a: G1 Point (64 bytes)
    /// - proof_b: G2 Point (128 bytes)
    /// - proof_c: G1 Point (64 bytes)
    /// - public_inputs: Vector of Fr field elements (32 bytes each)
    pub fn verify(
        env: Env,
        proof_a: G1Affine,
        proof_b: G2Affine,
        proof_c: G1Affine,
        public_inputs: Vec<Bn254Fr>,
    ) -> bool {{
        if public_inputs.len() as usize != NUM_PUBLIC_INPUTS {{
            return false;
        }}

        let bn = env.crypto().bn254();

        // 1. Single-Call Native Multi-Scalar Multiplication (Pippenger on host)
        // Eliminates O(N) host round-trips!
        let mut points: Vec<G1Affine> = Vec::new(&env);
{ic_rest_code}
        let msm_res = if points.is_empty() {{
            G1Affine::from_bytes(BytesN::from_array(&env, &VK_IC_0))
        }} else {{
            let msm_out = bn.g1_msm(&points, &public_inputs);
            let ic0 = G1Affine::from_bytes(BytesN::from_array(&env, &VK_IC_0));
            bn.g1_add(&ic0, &msm_out)
        }};

        // 2. Execute Groth16 4-Pairing Check natively on the validator:
        // e(-A, B) * e(alpha, beta) * e(vk_x, gamma) * e(C, delta) == 1
        let neg_a = -proof_a;

        let alpha = G1Affine::from_bytes(BytesN::from_array(&env, &VK_ALPHA_G1));
        let beta = G2Affine::from_bytes(BytesN::from_array(&env, &VK_BETA_G2));
        let gamma = G2Affine::from_bytes(BytesN::from_array(&env, &VK_GAMMA_G2));
        let delta = G2Affine::from_bytes(BytesN::from_array(&env, &VK_DELTA_G2));

        let g1_points = vec![&env, neg_a, alpha, msm_res, proof_c];
        let g2_points = vec![&env, proof_b, beta, gamma, delta];

        bn.pairing_check(g1_points, g2_points)
    }}
}}
"#,
        alpha_bytes = alpha_bytes,
        beta_bytes = beta_bytes,
        gamma_bytes = gamma_bytes,
        delta_bytes = delta_bytes,
        ic0_bytes = ic0_bytes,
        num_public_inputs = vk.nPublic,
        ic_rest_code = ic_rest_code,
    )
}

fn format_hex_array(parts: &[[u8; 32]]) -> String {
    let mut total = Vec::new();
    for p in parts {
        total.extend_from_slice(p);
    }
    format_bytes_literal(&total)
}

fn format_hex_g2(pt: &[[String; 2]; 3]) -> String {
    let x0 = crate::parser::parse_hex_or_dec_32(&pt[0][0]);
    let x1 = crate::parser::parse_hex_or_dec_32(&pt[0][1]);
    let y0 = crate::parser::parse_hex_or_dec_32(&pt[1][0]);
    let y1 = crate::parser::parse_hex_or_dec_32(&pt[1][1]);
    let mut total = [0u8; 128];
    total[0..32].copy_from_slice(&x0);
    total[32..64].copy_from_slice(&x1);
    total[64..96].copy_from_slice(&y0);
    total[96..128].copy_from_slice(&y1);
    format_bytes_literal(&total)
}

fn format_bytes_literal(bytes: &[u8]) -> String {
    let mut s = String::from("[\n    ");
    for (i, b) in bytes.iter().enumerate() {
        s.push_str(&format!("{:#04x}, ", b));
        if (i + 1) % 12 == 0 {
            s.push_str("\n    ");
        }
    }
    s.push_str("\n]");
    s
}
